#!/usr/bin/env python3
"""Writes LICENSES/rust-audio-crates.{md,txt}: notices and license texts of the
Rust crates the stem player links (normal dependencies of symphonia, hound,
signalsmith-stretch and rubato), read from the local Cargo registry.

Run from the repository root after changing those dependencies:
    python3 scripts/collect-audio-licenses.py
    pnpm exec biome format --write LICENSES/rust-audio-crates.md
"""
import json
import os
import subprocess
import sys

ROOTS = ["symphonia", "hound", "signalsmith-stretch", "rubato"]
# Preference when a crate offers a choice.
PREFERENCE = ["MIT", "0BSD", "Zlib", "Apache-2.0", "MPL-2.0"]
# Bundled C/C++ code inside a crate, noticed separately.
EMBEDDED = {
    "signalsmith-stretch": [
        ("Signalsmith Stretch 1.3.1 (C++)", "signalsmith-stretch/LICENSE.txt"),
        ("Signalsmith Linear (C++)", "signalsmith-linear/LICENSE.txt"),
    ],
}

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
manifest = os.path.join(root, "src-tauri", "Cargo.toml")
meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", manifest]))
packages = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
by_name = {p["name"]: p["id"] for p in meta["packages"]}

closure = set()
stack = [by_name[name] for name in ROOTS]
while stack:
    pid = stack.pop()
    if pid in closure:
        continue
    package = packages[pid]
    if any(t["kind"] == ["proc-macro"] for t in package["targets"]):
        continue  # runs at build time only; not in the app
    closure.add(pid)
    for dep in nodes[pid]["deps"]:
        if any(k["kind"] in (None, "normal") for k in dep["dep_kinds"]):
            stack.append(dep["pkg"])

def choose(expression):
    options = expression.replace("(", "").replace(")", "").replace(" AND ", " OR ").split(" OR ")
    options = [o.strip() for o in options]
    for preferred in PREFERENCE:
        if preferred in options:
            return preferred
    return options[0]

# Crates published without a license file: the text from their repository.
UPSTREAM = {"dasp": "LICENSES/upstream/dasp-LICENSE-MIT.txt"}

def license_files(directory, chosen):
    files = sorted(
        os.path.join(directory, name)
        for name in os.listdir(directory)
        if name.upper().startswith(("LICENSE", "LICENCE", "COPYING"))
        and os.path.isfile(os.path.join(directory, name))
    )
    if len(files) > 1:
        wanted = {"MIT": "MIT", "Apache-2.0": "APACHE", "0BSD": "0BSD", "Zlib": "ZLIB"}.get(chosen)
        matching = [f for f in files if wanted and wanted in os.path.basename(f).upper()]
        files = matching or files
    return files

rows = []
texts = []
for pid in sorted(closure, key=lambda p: packages[p]["name"]):
    package = packages[pid]
    directory = os.path.dirname(package["manifest_path"])
    chosen = choose(package["license"] or "")
    files = license_files(directory, chosen)
    family = package["name"].split("_")[0]
    if not files and family in UPSTREAM:
        files = [os.path.join(root, UPSTREAM[family])]
    repo = package.get("repository") or f"https://crates.io/crates/{package['name']}"
    rows.append(f"| {package['name']} | {package['version']} | {package['license']} | {chosen} | {repo} |")
    header = f"{package['name']} {package['version']} — {chosen}"
    if files:
        for path in files:
            with open(path, encoding="utf-8", errors="replace") as handle:
                texts.append(f"{'=' * 78}\n{header} ({os.path.basename(path)})\n{'=' * 78}\n\n{handle.read().strip()}\n")
    else:
        authors = ", ".join(package.get("authors") or []) or "the crate authors"
        texts.append(f"{'=' * 78}\n{header}\n{'=' * 78}\n\nNo license file in the published crate. "
                     f"Copyright (c) {authors}. Licensed under {chosen}; the full text is in this file "
                     f"under another crate with the same license.\n")
    for title, relative in EMBEDDED.get(package["name"], []):
        with open(os.path.join(directory, relative), encoding="utf-8") as handle:
            texts.append(f"{'=' * 78}\n{title}, bundled in {package['name']} {package['version']} — MIT\n"
                         f"{'=' * 78}\n\n{handle.read().strip()}\n")

out = os.path.join(root, "LICENSES")
with open(os.path.join(out, "rust-audio-crates.md"), "w", encoding="utf-8") as handle:
    handle.write("# Rust audio crates\n\n"
                 "Linked into the app for the stem player (decoding, time stretching, resampling, WAV I/O), "
                 "with every normal dependency. Generated by `scripts/collect-audio-licenses.py`; "
                 "the license texts are in [`rust-audio-crates.txt`](rust-audio-crates.txt). "
                 "Where a crate offers a choice, the app uses it under the license in the \"Used\" column.\n\n"
                 "Symphonia is MPL-2.0: the app uses its files unmodified, and their source is at "
                 "<https://github.com/pdeljanov/Symphonia> (tag `v0.6.1`) and on crates.io.\n\n"
                 "| Crate | Version | License | Used | Source |\n|---|---|---|---|---|\n")
    handle.write("\n".join(rows) + "\n")
with open(os.path.join(out, "rust-audio-crates.txt"), "w", encoding="utf-8") as handle:
    handle.write("\n".join(texts))
print(f"{len(rows)} crates", file=sys.stderr)
